namespace PanoramicData.Blazor;

/// <summary>
/// Identifies a media-control symbol for use in audio components.
/// </summary>
public enum Symbol
{
	/// <summary>No symbol is displayed.</summary>
	None,
	/// <summary>The skip-to-previous-track symbol.</summary>
	PreviousTrack,
	/// <summary>The play symbol.</summary>
	Play,
	/// <summary>The pause symbol.</summary>
	Pause,
	/// <summary>The skip-to-next-track symbol.</summary>
	NextTrack
}
