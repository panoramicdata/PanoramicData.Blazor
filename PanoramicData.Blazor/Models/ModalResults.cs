namespace PanoramicData.Blazor.Models;

/// <summary>
/// Provides string constants for standard modal dialog result values.
/// </summary>
public static class ModalResults
{
	/// <summary>Result string returned when the user cancels the dialog.</summary>
	public const string CANCEL = "Cancel";
	/// <summary>Result string returned when the user clicks No.</summary>
	public const string NO = "No";
	/// <summary>Result string returned when the user clicks Yes.</summary>
	public const string YES = "Yes";
}
