namespace PanoramicData.Blazor.Models;

/// <summary>
/// Specifies where the pager control is rendered relative to the data table.
/// </summary>
public enum PagerPositions
{
	/// <summary>Render the pager above the table.</summary>
	Top,
	/// <summary>Render the pager below the table.</summary>
	Bottom,
	/// <summary>Render the pager both above and below the table.</summary>
	Both
}
