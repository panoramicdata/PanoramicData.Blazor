namespace PanoramicData.Blazor.Enums;

/// <summary>
/// Specifies where tick-mark labels are rendered on a fader control.
/// </summary>
public enum PDFaderLabelPosition
{
	/// <summary>No labels are displayed.</summary>
	None,
	/// <summary>Labels are displayed on the left side of the fader track.</summary>
	Left,
	/// <summary>Labels are displayed on the right side of the fader track.</summary>
	Right,
	/// <summary>Labels are displayed on both sides of the fader track.</summary>
	Both
}
